def M1_crosswind_loop_recovery(records, physics):
    """Calibrate on a loop with a strong crosswind. The wind-blind fit is
    biased; the wind-aware fit (iteration 4) should recover (crr, CdA)."""
    calib = power_mod.calibrate_loop(records, RIDER, BIKE, weather_from(
        physics["wind_speed_mps"], physics["wind_dir_deg"]))
    if calib is None:
        return {"ok": False, "reason": "no calibration", "crr_err": float("inf"),
                "cdA_err": float("inf"), "n_segments": 0}
    wind_ok = True
    if calib.get("wind_recovered"):
        wind_ok = (abs(calib["wind_mps"] - physics["wind_speed_mps"]) <= 1.5
                   and min(abs(calib["wind_dir_deg"] - physics["wind_dir_deg"]),
                           360 - abs(calib["wind_dir_deg"] - physics["wind_dir_deg"])) <= 20.0)
    return {
        "ok": (abs(calib["crr"] - physics["crr"]) <= 0.0015
               and abs(calib["cdA"] - physics["cdA"]) <= 0.03 and wind_ok),
        "crr_err": abs(calib["crr"] - physics["crr"]),
        "cdA_err": abs(calib["cdA"] - physics["cdA"]),
        "wind_mps": round(calib.get("wind_mps") or 0.0, 2),
        "wind_dir": round(calib.get("wind_dir_deg") or 0.0, 1),
        "crr_sigma": round(calib.get("crr_sigma") or 0.0, 5),
        "cdA_sigma": round(calib.get("cdA_sigma") or 0.0, 4),
        "r2": round(calib.get("r2") or 0.0, 3),
        "n_segments": calib.get("n_segments", 0),
    }


def M1b_braked_loop_recovery(physics):
    """Calibration must stay sane when a descent has a 40 s braking window
    (speeds drop 15% with no change in elevation): the robust fit must not
    let the braked points inflate crr/CdA out of range."""
    loop = build_loop_ride(physics)
    for r in loop:
        if 350 <= r["t"] <= 390 and r["grade"] < -0.01:
            r["speed"] *= 0.82
    calib = power_mod.calibrate_loop(loop, RIDER, BIKE, weather_from(5.0, 90.0))
    if not calib:
        return {"ok": False, "reason": "no calibration", "crr_err": None}
    return {
        "ok": (abs(calib["crr"] - physics["crr"]) <= 0.003
               and abs(calib["cdA"] - physics["cdA"]) <= 0.07),
        "crr_err": round(abs(calib["crr"] - physics["crr"]), 5),
        "cdA_err": round(abs(calib["cdA"] - physics["cdA"]), 4),
    }


def M2_point_bias(records, model_records):
    """Median signed error (est - true) on pedalling points. Crosswind
    blindness biases flats low; after iteration 2 the bias should vanish."""
    errs = []
    for r, m in zip(records, model_records):
        if r["true_power_leg"] > 50 and m.get("mode") == "pedal":
            errs.append(m["watts_est"] - r["true_power_leg"])
    if not errs:
        return {"ok": False, "median": float("inf"), "n": 0}
    return {"ok": True, "median": float(np.median(errs)),
            "mae": float(np.mean(np.abs(errs))), "n": len(errs)}


def M3_climb_accuracy(records, model_records):
    """Median relative error on gravity-dominated (steep climb) points."""
    rel = []
    for r, m in zip(records, model_records):
        if r["true_power_leg"] > 100 and r["grade"] > 0.04 and m.get("mode") == "pedal":
            rel.append(abs(m["watts_est"] - r["true_power_leg"]) / r["true_power_leg"])
    if not rel:
        return {"ok": False, "med_rel": float("inf"), "n": 0}
    return {"ok": True, "med_rel": float(np.median(rel)), "n": len(rel)}


def M4_band_coverage(physics):
    """Coverage with matched wind noise: the simulated wind jitters each
    point by N(0, 2) m/s and the model is given that same sigma, so the
    band width is honest. Coverage should sit near 95% (2-sigma) and never
    below 90%."""
    windy = dict(physics, wind_speed_mps=5.0, wind_dir_deg=90.0)
    segs = [
        {"heading_deg": 90, "grade": 0.06, "dur_s": 300, "power": 260.0},
        {"heading_deg": 0, "grade": 0.0, "dur_s": 420, "power": 220.0},
        {"heading_deg": 180, "grade": -0.05, "dur_s": 240, "power": 0.0},
    ]
    records = simulate(segs, windy, seed=8, wind_noise_sigma=2.0)
    out = power_mod.compute_power(records, RIDER, BIKE,
                                  weather_from(5.0, 90.0, wind_sigma=2.0))
    inside = total = 0
    widths = []
    for r, m in zip(records, out):
        if r["true_power_leg"] > 50 and m.get("mode") == "pedal":
            total += 1
            if m["watts_lo"] <= r["true_power_leg"] <= m["watts_hi"]:
                inside += 1
            widths.append((m["watts_hi"] - m["watts_lo"]) / 2.0)
    cov = inside / total if total else 1.0
    rel_half = float(np.mean(widths) / max(np.mean(
        [m["watts_est"] for r, m in zip(records, out)
         if r["true_power_leg"] > 50 and m.get("mode") == "pedal"]), 1.0))
    # Coverage is the honesty gate (never below 90% even in the worst
    # case); the band is allowed to be conservative. Tightness is tracked
    # separately via rel_half_width and the calibrated-bike check (M10).
    return {"ok": cov >= 0.90, "coverage": round(cov, 3),
            "rel_half_width": round(rel_half, 2), "n": total}


def M11_power_curve(physics):
    """Best-N-minute power must recover known values: a constant 200 W ride
    gives ~206 W leg power everywhere; a 300 W surge lasting exactly 5 min
    must show up as the best-5-min value."""
    calm = dict(physics, wind_speed_mps=0.0, wind_dir_deg=0.0)

    def best5(segs, seed):
        records = simulate(segs, calm, seed=seed)
        out = power_mod.compute_power(records, RIDER, BIKE,
                                      weather_from(0.0, 0.0, wind_sigma=0.5))
        ts = np.array([r["t"] for r in out], dtype=float)
        w = np.array([r.get("watts_est") or 0.0 for r in out], dtype=float)
        return metrics_mod._best_power(w, ts, 300)

    steady = best5([{"heading_deg": 0, "grade": 0.0, "dur_s": 900, "power": 200.0}], 12)
    surge = best5([
        {"heading_deg": 0, "grade": 0.0, "dur_s": 300, "power": 300.0},
        {"heading_deg": 0, "grade": 0.0, "dur_s": 600, "power": 200.0},
    ], 13)
    leg_200 = 200.0 / 0.97
    leg_300 = 300.0 / 0.97
    ok = (abs(steady - leg_200) / leg_200 < 0.06
          and abs(surge - leg_300) / leg_300 < 0.06)
    return {"ok": ok, "steady_best5": round(steady, 0),
            "surge_best5": round(surge, 0), "expected": [round(leg_200), round(leg_300)]}


def M12_robust_watts_at_hr():
    """Watts@fixed-HR slope must survive a few outlier points: a clean
    watts = 2.0*(HR-100) ride plus 12 gust spikes at +300 W must keep a
    slope near 2.0 with the robust fit."""
    rng = random.Random(4)
    hrs = np.linspace(110, 175, 200)
    watts = 2.0 * (hrs - 100.0) + rng.gauss(0, 3.0)
    hrs_all = np.concatenate([hrs, hrs[:12] + np.array([rng.uniform(-8, 8) for _ in range(12)])])
    watts_all = np.concatenate([watts, watts[:12] + 300.0])
    conf = ["high"] * len(hrs_all)
    mode = ["pedal"] * len(hrs_all)
    r = metrics_mod._watts_at_fixed_hr(watts_all, hrs_all, conf, mode)
    est_140 = r["140"]["watts"]
    expected = 2.0 * (140 - 100.0)  # 80 W
    return {"ok": abs(est_140 - expected) < 12.0, "watts_at_140": est_140,
            "expected": expected}


def M13_wind_interpolation(physics):
    """On a 2 h ride where the wind rotates 90 deg, interpolating the hourly
    weather series must beat holding the start-hour wind."""
    calm = dict(physics, wind_speed_mps=0.0, wind_dir_deg=0.0)
    schedule = [(0, 5.0, 0.0), (3600, 5.0, 45.0), (7200, 5.0, 90.0)]
    segs = [{"heading_deg": 45, "grade": 0.0, "dur_s": 7200, "power": 220.0}]
    records = simulate(segs, calm, seed=14, wind_schedule=schedule)

    # Weather with the hourly series (ride starts at hour 14).
    dir_hourly = [0.0] * 24
    dir_hourly[14], dir_hourly[15], dir_hourly[16] = 0.0, 45.0, 90.0
    hourly = {"temp_c": 15.0, "pressure_hpa": 1013.0,
              "wind_speed_mps": 5.0, "wind_dir_deg": 0.0,
              "wind_sigma_mps": 1.0, "ride_hour": 14,
              "wind_speed_hourly": [5.0] * 24, "wind_dir_hourly": dir_hourly}
    single = {"temp_c": 15.0, "pressure_hpa": 1013.0,
              "wind_speed_mps": 5.0, "wind_dir_deg": 0.0,
              "wind_sigma_mps": 1.0}

    def mae(out):
        errs = [abs(m["watts_est"] - r["true_power_leg"])
                for r, m in zip(records, out)
                if r["true_power_leg"] > 50 and m.get("mode") == "pedal"]
        return float(np.mean(errs)) if errs else float("inf")

    a = mae(power_mod.compute_power(records, RIDER, BIKE, single))
    b = mae(power_mod.compute_power(records, RIDER, BIKE, hourly))
    return {"ok": b < a, "mae_single_hour": round(a, 1),
            "mae_interpolated": round(b, 1), "n": 7200}


def M10_calibrated_bands(physics):
    """A calibrated bike must get strictly narrower bands than the same
    bike uncalibrated, while coverage stays honest (>= 0.90)."""
    loop = build_loop_ride(physics)
    calib = power_mod.calibrate_loop(loop, RIDER, BIKE, weather_from(5.0, 90.0))
    if not calib or not calib.get("crr_sigma"):
        return {"ok": False, "reason": "no calibration", "ratio": None}
    bike_cal = dict(BIKE, crr=calib["crr"], cdA=calib["cdA"],
                    calibrated=True, calibration=calib)
    out_unc = power_mod.compute_power(loop, RIDER, BIKE, weather_from(5.0, 90.0))
    out_cal = power_mod.compute_power(loop, RIDER, bike_cal, weather_from(5.0, 90.0))

    def stats(out):
        inside = total = 0
        widths = []
        for r, m in zip(loop, out):
            if r["true_power_leg"] > 50 and m.get("mode") == "pedal":
                total += 1
                if m["watts_lo"] <= r["true_power_leg"] <= m["watts_hi"]:
                    inside += 1
                widths.append(m["watts_hi"] - m["watts_lo"])
        return inside / total if total else 1.0, float(np.mean(widths))

    cov_unc, w_unc = stats(out_unc)
    cov_cal, w_cal = stats(out_cal)
    ratio = w_cal / w_unc if w_unc > 0 else 1.0
    return {"ok": ratio < 0.95 and cov_cal >= 0.90,
            "width_ratio": round(ratio, 3), "cov_cal": round(cov_cal, 3),
            "cov_unc": round(cov_unc, 3)}


def M7_high_elevation(physics):
    """A flat ride at ~2000 m with known power must be recovered: the
    ~20% density drop must flow through the estimate consistently. Uses
    zero wind so the density effect is isolated."""
    calm = dict(physics, wind_speed_mps=0.0, wind_dir_deg=0.0)
    segs = [{"heading_deg": 45, "grade": 0.0, "dur_s": 600, "power": 200.0}]
    records = simulate(segs, calm, seed=9, start_elev=2000.0)
    out = power_mod.compute_power(records, RIDER, BIKE, weather_from(0.0, 0.0))
    errs = [m["watts_est"] - r["true_power_leg"]
            for r, m in zip(records, out)
            if r["true_power_leg"] > 50 and m.get("mode") == "pedal"]
    if not errs:
        return {"ok": False, "median": float("inf"), "n": 0}
    med = float(np.median(errs))
    return {"ok": abs(med) <= 5.0, "median": med, "n": len(errs)}


def M8_wind_reapply(records, physics):
    """The wind the calibration recovers must improve the ride's estimates
    when the weather forecast was wrong. Here the weather says calm but the
    true wind is 5 m/s crosswind; re-applying the recovered wind should cut
    the mean absolute error on pedalling points."""
    wrong = weather_from(0.0, 0.0)
    calib = power_mod.calibrate_loop(records, RIDER, BIKE, wrong)
    if not calib or not calib.get("wind_recovered"):
        return {"ok": False, "reason": "no wind recovered", "mae_base": None,
                "mae_reapplied": None}
    out_base = power_mod.compute_power(records, RIDER, BIKE, wrong)
    eff = weather_from(calib["wind_mps"], calib["wind_dir_deg"])
    out_re = power_mod.compute_power(records, RIDER, BIKE, eff)

    def mae(out):
        errs = [abs(m["watts_est"] - r["true_power_leg"])
                for r, m in zip(records, out)
                if r["true_power_leg"] > 50 and m.get("mode") == "pedal"]
        return float(np.mean(errs)) if errs else float("inf")

    a, b = mae(out_base), mae(out_re)
    return {"ok": b <= a * 0.7, "mae_base": round(a, 1),
            "mae_reapplied": round(b, 1), "n": 1020}


def M9_climb_calibration(physics):
    """The climb-Crr calibration must recover crr on a steep climb, using
    the model's own (gravity-dominated) power estimate as energy input."""
    calm = dict(physics, wind_speed_mps=0.0, wind_dir_deg=0.0)
    seg = [{"heading_deg": 0, "grade": 0.07, "dur_s": 400, "power": 260.0},
           {"heading_deg": 0, "grade": 0.02, "dur_s": 60, "power": 120.0},
           {"heading_deg": 0, "grade": 0.06, "dur_s": 400, "power": 250.0}]
    records = simulate(seg, calm, seed=5)
    out = power_mod.compute_power(records, RIDER, BIKE, weather_from(0.0, 0.0))
    calib = power_mod.calibrate_climb(out, RIDER, BIKE, weather_from(0.0, 0.0))
    if not calib:
        return {"ok": False, "reason": "no climb segments", "crr_err": None}
    err = abs(calib["crr"] - physics["crr"])
    return {"ok": err <= 0.003, "crr_err": round(err, 5),
            "n_segments": calib["n_segments"],
            "crr_sigma": round(calib.get("crr_sigma") or 0.0, 5)}


def M5_coasting(records, model_records):
    """Coasting descents must be flagged coast; light pedalling with an
    elevated HR must not."""
    coast_pts = sum(1 for r in records if r["true_power_leg"] == 0 and r["grade"] < -0.01)
    coast_flag = sum(1 for r, m in zip(records, model_records)
                     if r["true_power_leg"] == 0 and r["grade"] < -0.01 and m.get("mode") == "coast")
    false_coast = sum(1 for r, m in zip(records, model_records)
                      if r["true_power_leg"] > 100 and m.get("mode") == "coast")
    rate = coast_flag / coast_pts if coast_pts else 1.0
    return {"ok": rate >= 0.95 and false_coast == 0,
            "rate": rate, "false_coast": false_coast}


def M6_real_ride():
    """Plausibility on the repo's real .fit file (device altitude, no
    network). Power must be finite and in a sane window on pedalling pts."""
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    fits = sorted(f for f in os.listdir(root) if f.lower().endswith(".fit"))
    if not fits:
        return {"ok": True, "reason": "no .fit file present", "n": 0}
    from cycling import fit_parser
    records, _ = fit_parser.parse_fit(os.path.join(root, fits[0]))
    if not records:
        return {"ok": False, "reason": "unparseable .fit"}
    # Device altitude -> smooth grade (no network; approximate).
    alts = np.array([r.get("alt_raw") or 0.0 for r in records], dtype=float)
    alts = np.convolve(alts, np.ones(31) / 31.0, mode="same")
    d = np.diff(alts)
    dt = np.diff([r["t"] for r in records])
    with np.errstate(divide="ignore", invalid="ignore"):
        vv = np.array([r.get("speed") or 0.0 for r in records], dtype=float)
        grade = np.where(dt > 0, d / np.maximum(vv[:-1] * dt, 1e-6), 0.0)
    grade = np.clip(grade, -0.2, 0.2)
    for i, r in enumerate(records):
        r["elev"] = float(alts[i])
        r["grade"] = float(grade[i]) if i < len(grade) else float(grade[-1])
    # Drop trailing points with degenerate dt (device stop).
    records = [r for r in records if r.get("speed") or 0.0 > 0.5]
    out = power_mod.compute_power(records, RIDER, BIKE, weather_from(0.0, 0.0))
    ws = np.array([m.get("watts_est") or 0.0 for m in out])
    pedal = ws > 5.0
    if not np.isfinite(ws).all() or not pedal.any():
        return {"ok": False, "reason": "non-finite or no pedalling"}
    med = float(np.median(ws[pedal]))
    ok = 15.0 <= med <= 400.0
    return {"ok": ok, "median_watts": med, "n": int(pedal.sum()),
            "file": fits[0]}


