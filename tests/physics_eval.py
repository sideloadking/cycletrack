def build_loop_ride(physics, seed=2):
    """Rectangular loop with coasting descents on all four headings."""
    hw, cw = wind_components(physics["wind_speed_mps"], physics["wind_dir_deg"], 0.0)
    segs = []
    for heading in (0, 90, 180, 270):
        v_goal = {0: 7.5, 90: 6.0, 180: 8.5, 270: 6.5}[heading]
        g = coast_grade(physics["crr"], physics["cdA"], physics["rho"], v_goal,
                        physics["wind_speed_mps"], physics["wind_dir_deg"], heading,
                        physics["mass_kg"])
        segs.append({"heading_deg": heading, "grade": 0.05, "dur_s": 90, "power": 260.0})
        segs.append({"heading_deg": heading, "grade": g, "dur_s": 150, "power": 0.0})
    return simulate(segs, physics, seed=seed)


def build_ride(physics, seed=3):
    """Climb (headwind) + pure-crosswind flat + coast descent + climb
    (tailwind). The flat is at heading 0 with wind from 90 deg, so hw=0 and
    the whole aero error there is crosswind."""
    segs = [
        {"heading_deg": 90, "grade": 0.06, "dur_s": 300, "power": 260.0},
        {"heading_deg": 0, "grade": 0.0, "dur_s": 420, "power": 220.0},
        {"heading_deg": 180, "grade": -0.05, "dur_s": 240, "power": 0.0},
        {"heading_deg": 270, "grade": 0.05, "dur_s": 300, "power": 250.0},
    ]
    return simulate(segs, physics, seed=seed)


