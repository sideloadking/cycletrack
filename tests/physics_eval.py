"""Physics eval harness — the quality gate for the physics-backend loop.

Synthetic rides are generated by forward-integrating the *true* dynamics
(including crosswind, which the current model ignores) with known
(crr, CdA, wind, mass, rho). The harness then measures how well the
power model recovers the injected physics. Run standalone:

    python tests/physics_eval.py

Each check prints a numeric metric. The loop's gate rule: an iteration
must not regress any check and must improve at least one target metric
(recorded in docs/superpowers/specs/physics-eval-results.md).
"""

import math
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np

from cycling import config, metrics as metrics_mod, power as power_mod

G = 9.80665
EFF = 0.97
INERTIA = 1.05
KIT = 2.0

RIDER = {"weight_kg": 75.0, "max_hr": 180, "age": 40}
BIKE = {"mass_kg": 9.0, "crr": 0.005, "cdA": 0.35, "drivetrain_efficiency": EFF}
MASS = RIDER["weight_kg"] + BIKE["mass_kg"] + KIT  # 86.0 kg


def true_rho():
    return 101325.0 / (287.05 * 288.15)


def wind_components(wind_speed, wind_dir_deg, heading_deg):
    """Headwind (+) and crosswind components, matching power.py's sign
    convention: wind_dir_deg is the direction the wind comes FROM, heading
    is the direction of travel (deg clockwise from north)."""
    wr = math.radians(wind_dir_deg)
    brg = math.radians(heading_deg)
    hw = wind_speed * math.cos(wr - brg)
    cw = wind_speed * math.sin(wr - brg)
    return hw, cw


def aero_force(crr_physics, cdA, rho, v, hw, cw, mass):
    """True aero drag force opposing motion, including crosswind."""
    v_air = math.sqrt((v + hw) ** 2 + cw ** 2)
    return 0.5 * rho * cdA * v_air * (v + hw)


def coast_grade(crr, cdA, rho, v, wind_speed, wind_dir_deg, heading_deg, mass):
    """Grade that makes ``v`` an equilibrium coast speed (zero rider power),
    with crosswind included. Solve m g sin(theta) = roll + aero."""
    hw, cw = wind_components(wind_speed, wind_dir_deg, heading_deg)

    def loss(theta):
        # Net opposing force: roll + aero + gravity term (negative on a
        # descent). Zero means the descent grade balances the losses.
        g_term = mass * G * math.sin(theta)
        roll = crr * mass * G * math.cos(theta)
        aero = aero_force(crr, cdA, rho, v, hw, cw, mass)
        return roll + aero + g_term

    lo, hi = -0.20, 0.0
    # loss(lo) < 0 (steep descent over-assists), loss(hi) > 0 (flat needs
    # pedalling): the zero crossing is the equilibrium grade.
    for _ in range(60):
        mid = 0.5 * (lo + hi)
        if loss(mid) > 0:
            hi = mid
        else:
            lo = mid
    return 0.5 * (lo + hi)


def _interp_wind(schedule, t):
    """Linear (circular for direction) interpolation of a wind schedule:
    list of (t_seconds, speed, dir_deg)."""
    times = [s[0] for s in schedule]
    spds = [s[1] for s in schedule]
    drs = [math.radians(s[2]) for s in schedule]
    w = np.interp(t, times, spds)
    xs = np.interp(t, times, np.cos(drs))
    ys = np.interp(t, times, np.sin(drs))
    return float(w), math.degrees(math.atan2(ys, xs)) % 360.0


def simulate(segments, physics, dt=1.0, seed=1, noise=True, start_elev=120.0,
             wind_noise_sigma=0.0, wind_schedule=None):
    """Forward-integrate the true dynamics.

    ``segments``: list of dicts with heading_deg, grade, dur_s, power
    (wheel watts; 0 = coast), and optional hr.
    ``physics``: crr, cdA, rho, wind_speed_mps, wind_dir_deg, mass_kg.
    Air density is elevation-dependent (barometric), matching the model.
    Returns list of record dicts (t, lat, lon, speed, dist, elev, grade,
    hr, true_power_leg)."""
    rng = random.Random(seed)
    crr = physics["crr"]
    cdA = physics["cdA"]
    ws = physics["wind_speed_mps"]
    wd = physics["wind_dir_deg"]
    mass = physics["mass_kg"]
    weather = {"temp_c": 15.0, "pressure_hpa": 1013.0}

    records = []
    t = 0.0
    lat, lon = 52.0, -1.5
    dist = 0.0
    elev = start_elev
    v = 3.0
    lat_deg_per_m = 1.0 / 111320.0
    wind_err = lambda: rng.gauss(0.0, wind_noise_sigma) if wind_noise_sigma > 0 else 0.0
    if wind_schedule:
        def wind_at(t):
            return _interp_wind(wind_schedule, t)
    else:
        def wind_at(t):
            return ws, wd

    for seg in segments:
        heading = math.radians(seg["heading_deg"])
        n = max(2, int(round(seg["dur_s"] / dt)))
        for i in range(n):
            w_scalar, w_dir = wind_at(t)
            hw0, cw0 = wind_components(w_scalar, w_dir, seg["heading_deg"])
            hw = hw0 + wind_err()
            cw = cw0 + wind_err()
            theta = math.atan(seg["grade"])
            roll = crr * mass * G * math.cos(theta)
            rho = power_mod.elevation_air_density(weather, [elev]).item()
            aero = aero_force(crr, cdA, rho, v, hw, cw, mass)
            grav = mass * G * math.sin(theta)
            f_rider = seg["power"] / v if (seg["power"] > 0 and v > 0.4) else 0.0
            dv = (f_rider - roll - aero - grav) / (mass * INERTIA)
            v_new = v + dv * dt
            if v_new < 0.0:
                v_new = 0.0
                dv = -v / dt
            # Speed sensor noise: ~1% Gaussian.
            v_sensed = v * (1.0 + (rng.gauss(0, 0.01) if noise else 0.0))
            grade_sensed = seg["grade"] + (rng.gauss(0, 0.002) if noise else 0.0)
            d = v * dt
            lat += d * math.cos(heading) * lat_deg_per_m
            lon += d * math.sin(heading) * (lat_deg_per_m / math.cos(math.radians(lat)))
            dist += d
            elev += seg["grade"] * d
            if seg.get("hr") is not None:
                hr = seg["hr"]
            elif seg["power"] > 100:
                hr = 145.0 + seg["grade"] * 600.0
            else:
                hr = 95.0
            p_leg = (seg["power"] * 1.0) / EFF if seg["power"] > 0 else 0.0
            records.append({
                "t": t, "lat": lat, "lon": lon, "speed": v_sensed,
                "dist": dist, "elev": elev, "grade": grade_sensed,
                "hr": hr, "true_power_leg": p_leg,
            })
            v = v_new
            t += dt
    return records


def weather_from(wind_speed, wind_dir_deg, wind_sigma=1.0):
    return {"temp_c": 15.0, "pressure_hpa": 1013.0,
            "wind_speed_mps": wind_speed, "wind_dir_deg": wind_dir_deg,
            "wind_sigma_mps": wind_sigma}


